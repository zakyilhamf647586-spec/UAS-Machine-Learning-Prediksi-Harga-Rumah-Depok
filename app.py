"""Streamlit demo for the validated *in-scope* academic Depok house-price model.

Only load model files generated by train_model.py from sources you trust.
"""
from pathlib import Path
import json
import math
import joblib
import pandas as pd
import streamlit as st

BASE = Path(__file__).resolve().parent
INPUTS = ['Kamar Tidur','Kamar Mandi','Garasi','Luas Tanah','Luas Bangunan','Lokasi']

st.set_page_config(page_title='Estimasi Harga Rumah Depok',page_icon='🏠',layout='wide')

@st.cache_resource

def load_pipeline():
    # A joblib/pickle file can execute code while loading. Trust its origin.
    return joblib.load(BASE/'models'/'house_price_pipeline.joblib')

@st.cache_data

def load_metrics():
    return json.loads((BASE/'metrics.json').read_text(encoding='utf-8'))

try:
    model = load_pipeline()
    metrics = load_metrics()
except Exception as exc:
    st.error(f'Berkas model atau metrik belum tersedia: {exc}')
    st.info('Jalankan `python train_model.py` dari folder proyek untuk membuat artefak yang konsisten.')
    st.stop()

st.title('🏠 Estimasi Harga Rumah di Depok')
st.caption('Proyek akademik berbasis Machine Learning — bukan penilaian pasar resmi atau saran transaksi.')
st.info('Cakupan evaluasi: harga Rp100 juta–Rp10 miliar; luas tanah/bangunan 20–1.500 m²; kamar tidur/mandi 1–15; garasi 0–10. Prediksi di luar cakupan tersebut tidak divalidasi.')

with st.sidebar:
    st.subheader('📊 Evaluasi pada data uji')
    selected = metrics['selected']
    st.metric('Algoritma', selected)
    st.metric('R²', f"{metrics['models'][selected]['R2']:.3f}")
    st.metric('MAE', f"Rp {metrics['models'][selected]['MAE_Rp']/1e6:,.1f} juta")
    st.metric('Jumlah data uji', f"{metrics['test_rows']:,}".replace(',', '.'))
    st.caption('Hasil satu pembagian holdout berbasis kelompok fitur identik. Belum menggunakan cross-validation atau data eksternal.')

left, right = st.columns([1,1],gap='large')
with left:
    st.subheader('Spesifikasi rumah')
    bedroom = st.number_input('Kamar tidur',min_value=1,max_value=15,value=3,step=1)
    bathroom = st.number_input('Kamar mandi',min_value=1,max_value=15,value=2,step=1)
    garage = st.number_input('Garasi',min_value=0,max_value=10,value=1,step=1)
    land = st.number_input('Luas tanah (m²)',min_value=20,max_value=1500,value=120,step=1)
    building = st.number_input('Luas bangunan (m²)',min_value=20,max_value=1500,value=100,step=1)
    # Location list comes from training encoder; never independently encode a single row.
    location_encoder = model.named_steps['prep'].named_transformers_['location']
    locations = sorted(map(str,location_encoder.categories_[0]))
    location = st.selectbox('Lokasi',options=locations)
    predict = st.button('Prediksi harga',type='primary',use_container_width=True)

with right:
    st.subheader('Hasil estimasi')
    if predict:
        row = pd.DataFrame([{
            'Kamar Tidur': bedroom,'Kamar Mandi': bathroom,'Garasi': garage,
            'Luas Tanah':land,'Luas Bangunan':building,'Lokasi':location,
        }],columns=INPUTS)
        price = float(model.predict(row)[0])
        if not math.isfinite(price) or price <= 0:
            st.error('Model menghasilkan nilai tidak valid. Perlu pemeriksaan ulang.')
        else:
            st.metric('Perkiraan harga',f"Rp {price:,.0f}".replace(',','.'))
            st.metric('Harga per m² luas bangunan',f"Rp {price/building:,.0f}".replace(',','.'))
            if not 100_000_000 <= price <= 10_000_000_000:
                st.warning('Prediksi di luar rentang harga evaluasi. Interpretasikan dengan sangat hati-hati.')
            st.caption('Estimasi dapat meleset jauh dari harga aktual, khususnya pada properti mahal. Jangan digunakan sebagai dasar tunggal keputusan finansial.')
    else:
        st.write('Masukkan spesifikasi dan klik tombol prediksi untuk melihat hasil.')

st.divider()
st.subheader('Kinerja menurut rentang harga aktual')
st.caption('Evaluasi dilakukan pada data uji, dikelompokkan berdasarkan harga aktual. Rentang harga tinggi memiliki kesalahan rata-rata lebih besar.')
bands = metrics['test_MAE_by_actual_price_band']
for name, stat in bands.items():
    a,b = st.columns([2,1]);a.write(f'{name} ({stat["n"]:,} sampel)');b.write(f"MAE Rp {stat['MAE_Rp']/1e6:,.1f} juta")

if metrics['selected']=='Random Forest':
    st.divider()
    st.subheader('Feature importance (indikatif, bukan kausalitas)')
    prep = model.named_steps['prep']
    names = prep.get_feature_names_out()
    importance = pd.DataFrame({'Fitur': names,'Importance':model.named_steps['model'].feature_importances_})
    # Group all one-hot location columns to show a more interpretable summary.
    importance['Fitur'] = importance['Fitur'].map(lambda n: 'Lokasi (gabungan)' if n.startswith('location__') else n.replace('numeric__',''))
    imp = importance.groupby('Fitur',as_index=False)['Importance'].sum().sort_values('Importance',ascending=False)
    st.bar_chart(imp.set_index('Fitur'))

st.divider()
st.caption('Sumber dataset serta izin penggunaannya perlu didokumentasikan sebelum publikasi atau pemakaian di luar konteks akademik.')
